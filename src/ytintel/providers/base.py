"""Dependency inversion boundary used by orchestration and both adapters."""

from typing import Protocol

from ..domain import Video


class Provider(Protocol):
    async def videos(self, ids: list[str]) -> list[Video]: ...
    async def search(self, query: str, language: str | None = None) -> list[Video]: ...
    async def channel(self, ref: str) -> dict: ...
    async def search_channels(self, query: str) -> list[dict]: ...
    async def profile(self) -> dict: ...
    async def create_playlist(self, title: str) -> str: ...
    async def add_video(self, playlist_id: str, video_id: str) -> None: ...
